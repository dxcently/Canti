/// 1-bit bitmap glyphs for the pixel kit (lib/src/theme/pixel.dart): `#` is a lit pixel, anything else is empty.
/// Drawn by [PixelGlyph] at the pixel scale, never resampled, so they stay as sharp as the fonts.
///
/// Sizes: gesture glyphs 12x12 (the bindings grid), row and button icons 7x7, small marks 5x5.
library;

class Glyph {
  const Glyph(this.rows);

  final List<String> rows;

  int get width => rows.first.length;
  int get height => rows.length;
}

